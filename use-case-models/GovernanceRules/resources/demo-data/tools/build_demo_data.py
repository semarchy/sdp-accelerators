#!/usr/bin/env python3
"""Build the GovernanceRules demo data from its editable source.

Purpose
    Generates, from the JSON files in ../source/, the two load formats of the
    GovernanceRules accelerator test dataset:
      - ../data-files/NN-<Entity>.csv   one CSV per entity, NN = safe load order
                                        (for the UI import or any file-based loader);
      - ../API Import-curl/GovernanceRules-demo-data.json
                                        one CREATE_LOAD_AND_SUBMIT payload for the
                                        REST loads API (see HowTo_CallInitDataLoadCurl.md).
    Both carry the same records: the curated corpus (source/<Entity>.json) followed
    by the three deliberate validation failures (source/_deliberate-failures.json).

Conventions applied
    - Column / key names are the SEML attribute names; a reference to a basic
      entity is written FID_<role name> and holds the target Code.
    - RuleScope and RuleCitation have no ID column: their ID is generated by a
      SEQUENCE at load time.
    - InForce (GovernanceRule) is computed by the ComputeInForce enricher and is
      never written.
    - CSV: UTF-8 (no BOM), comma-separated, LF line ends, dates yyyy-MM-dd,
      booleans true/false, nulls as empty cells.
    - JSON payload: null attributes are omitted; optionsPerEntity lists every
      entity with empty enricher and validation lists (required by the API;
      the certification job still runs every enricher and validation).
    - Output is deterministic (source order, fixed column order): rebuilding an
      unchanged source gives byte-identical files.

Usage
    python build_demo_data.py            build the files
    python build_demo_data.py --check    build in memory and fail (exit 1) if the
                                         files on disk differ from the source
    Then run validate_demo_data.py.

Standard library only. Paths are relative to this script. Exit code 1 on failure.
"""
import argparse
import csv
import io
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, ".."))
SOURCE = os.path.join(ROOT, "source")
DATA_FILES = os.path.join(ROOT, "data-files")
API_DIR = os.path.join(ROOT, "API Import-curl")
PAYLOAD = os.path.join(API_DIR, "GovernanceRules-demo-data.json")
FAILURES = os.path.join(SOURCE, "_deliberate-failures.json")

# Load order (parents before children, same order as the INTEGRATE_ALL job).
# For each entity: the attributes written, in SEML order, then the references as
# (source JSON key, FID column). The source key is the reference role name.
SPEC = [
    ("GovernanceBody", ["Code", "Name", "Type", "ContactEmail", "Description"], []),
    ("DataDomain", ["Code", "Name", "Description"], []),
    ("DataClassification", ["Code", "Name", "Description", "SensitivityRank"], []),
    ("Regulation", ["Code", "Name", "Type", "Issuer", "Jurisdiction", "URL", "Description"], []),
    ("BusinessAttributeType", ["Code", "Name", "Description", "FormatPattern", "Example"],
     [("DefaultClassification", "FID_DefaultClassification"), ("ReferenceStandard", "FID_ReferenceStandard")]),
    ("GovernancePolicy", ["Code", "Name", "Description", "Purpose", "LifecycleStatus"],
     [("OwnerBody", "FID_OwnerBody")]),
    ("GovernanceRule", ["Code", "Title", "Statement", "Rationale", "RequirementLevel", "Category",
                        "ImplementationPattern", "ImplementationGuidance", "Example", "LifecycleStatus",
                        "EffectiveDate", "RetirementDate", "RetirementReason", "ApprovedOn", "ApprovedBy"],
     [("Policy", "FID_Policy"), ("OwnerBody", "FID_OwnerBody")]),
    ("RuleScope", [],
     [("Rule", "FID_Rule"), ("DataDomain", "FID_DataDomain"), ("DataClassification", "FID_DataClassification"),
      ("AttributeType", "FID_AttributeType")]),
    ("RuleCitation", ["Clause", "Note"], [("Rule", "FID_Rule"), ("Regulation", "FID_Regulation")]),
]

PAYLOAD_HEAD = {
    "action": "CREATE_LOAD_AND_SUBMIT",
    "programName": "curl",
    "loadDescription": None,  # filled with the counts
    "jobName": "INTEGRATE_ALL",
    "persistOptions": {
        "responsePayload": "SUMMARY",
        "persistMode": "ALWAYS",
        "defaultPublisherId": "SEED",
        "optionsPerEntity": None,  # filled: every entity, no persist-time enricher or validation
        "missingIdBehavior": "GENERATE",
    },
}


def load_json(path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def records():
    """Yield (entity, columns, rows) with rows as ordered dicts keyed by column name."""
    failures = load_json(FAILURES)
    for entity, attrs, refs in SPEC:
        src = load_json(os.path.join(SOURCE, entity + ".json"))
        src = src + failures.get(entity, [])
        columns = attrs + [fid for _, fid in refs]
        rows = []
        for i, r in enumerate(src, 1):
            known = set(attrs) | {k for k, _ in refs}
            unknown = sorted(set(r) - known)
            if unknown:
                raise ValueError(f"{entity} row {i}: unknown key(s) {unknown} in source")
            row = {a: r.get(a) for a in attrs}
            row.update({fid: r.get(key) for key, fid in refs})
            rows.append(row)
        yield entity, columns, rows


def csv_text(columns, rows):
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n", quoting=csv.QUOTE_MINIMAL)
    w.writerow(columns)
    for row in rows:
        out = []
        for c in columns:
            v = row[c]
            if v is None:
                out.append("")
            elif isinstance(v, bool):
                out.append("true" if v else "false")
            else:
                out.append(str(v))
        w.writerow(out)
    return buf.getvalue()


def build():
    """Return {path: text} for every generated file."""
    files, persist, counts = {}, {}, []
    for n, (entity, columns, rows) in enumerate(records(), 1):
        files[os.path.join(DATA_FILES, f"{n:02d}-{entity}.csv")] = csv_text(columns, rows)
        persist[entity] = [{k: v for k, v in row.items() if v is not None} for row in rows]
        counts.append(f"{entity} {len(rows)}")
    payload = dict(PAYLOAD_HEAD)
    payload["persistOptions"] = dict(PAYLOAD_HEAD["persistOptions"])
    # The loads API refuses a payload whose optionsPerEntity does not list every
    # entity ("optionsPerEntity is required"). Empty lists = no enricher or
    # validation at persist time; the INTEGRATE_ALL job still runs them all.
    payload["persistOptions"]["optionsPerEntity"] = {e: {"enrichers": [], "validations": []} for e in persist}
    payload["loadDescription"] = ("GovernanceRules demo data, publisher SEED (" + ", ".join(counts)
                                  + "; GovernanceRule includes 3 deliberate validation failures DQ-BAD1..3)")
    payload["persistRecords"] = persist
    files[PAYLOAD] = json.dumps(payload, indent=2, ensure_ascii=False) + "\n"
    return files


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true",
                    help="do not write; exit 1 if the generated files on disk are not up to date")
    args = ap.parse_args()
    try:
        files = build()
    except (OSError, ValueError, KeyError) as e:
        print(f"ERROR: {e}")
        return 1
    stale = []
    for path, text in files.items():
        rel = os.path.relpath(path, ROOT)
        current = None
        if os.path.exists(path):
            with open(path, encoding="utf-8", newline="") as f:
                current = f.read()
        if args.check:
            if current != text:
                stale.append(rel)
            continue
        if current != text:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w", encoding="utf-8", newline="") as f:
                f.write(text)
            print(f"written   {rel} ({len(text.encode('utf-8'))} bytes)")
        else:
            print(f"unchanged {rel}")
    if stale:
        print("Out of date (run build_demo_data.py):", ", ".join(stale))
        return 1
    if args.check:
        print("OK - generated files are up to date with source/")
    return 0


if __name__ == "__main__":
    sys.exit(main())
